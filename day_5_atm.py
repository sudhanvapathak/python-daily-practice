balence = 1000
while True:
  flag = int(input("Choose the following:\n 1. Current Balence\n 2. Deposite\n 3. Withdraw\n 4. Exit\n"))
  if (flag == 1 ):
    print(f"Current balence is: $", balence)
  elif (flag == 2):
    deposite = int(input("Enter amount to deposite:"))
    if(deposite <= 0):
      print("Amount must be greater than 0!")
    else:
      balence = balence + deposite
      print(f"You have successfully deposited $", deposite ,"\nCurrent balence is $", balence)
  elif(flag == 3):
    withdraw = int(input("Enter amount to withdraw:"))
    if(withdraw <=0):
      print("Amount must be greater than 0!")
    elif(withdraw > balence):
      print(f"You do not have enough funds!\nCurrent balence is: $", balence)
    else:
      balence = balence - withdraw
      print(f"You have withdrawn $", withdraw,"\nCurrent balence is $", balence)
  else:
    print("Thank you!")
    break

