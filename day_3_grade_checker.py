score = int(input("Please enter your grade:"))

if (score > 100 or score < 0):
  print("Invalid Score!")
elif(score >= 90):
  print("Grade A")
elif(score>=80 and score<=89):
  print("Grade B")
elif(score>=70 and score<=79):
  print("Grade C")
elif(score>=60 and score<=69):
  print("Grade D")
else:
  print("Grade F")

