import random
secret = random.randint(1,100)
tries = 0
guess = 0
while guess!=secret:
  guess = int(input("Guess the number:"))
  if(guess < secret):
    print("You guessed low, Try again")
    tries += 1
  elif (guess > secret):
    print("You guessed too high, try again!")
    tries += 1
  elif(guess == secret):
    print("You guessed right!")
    tries += 1
    print(f"You took ", tries, "tries")

