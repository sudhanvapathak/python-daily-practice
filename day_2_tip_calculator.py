bill = float(input("Enter total bill:"))
tip = float(input("Enter the tip:"))
split = int(input("How many people splitting the bill"))

tip = bill * tip/100
total_bill = bill + tip
split_bill = total_bill/split

print(f"Total: ${total_bill:.2f}")
print(f"Calculated tip: ${tip:.2f}")
print(f"Each share: ${split_bill:.2f}")

